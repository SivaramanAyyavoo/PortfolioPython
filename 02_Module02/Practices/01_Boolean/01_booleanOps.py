var = 5

#Equality Operators
print(var == 5)     # equal to
print(var == 5.)
print(var == 3)

print(var != 3)     # not equal to

#Comparison Operators
print(var > 3)      # greater than
print(var < 3)      # lesser than

print(var >= 3)     # greater than or equal to
print(var <= 3)     # lesser than or equal to
