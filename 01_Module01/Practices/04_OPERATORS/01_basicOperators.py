#binary operators
print(5 + 3)    #addition
print(5 - 3)    #substraction
print(5 * 3)    #multiplication
print(5 / 3)    #division
print(5 // 3)   #integer division / floor division
print(5 % 3)    #remainder / modulo
print(5 ** 3)   #Exponentiation


# NOTE 1: All the operators return float result (either both or one of the value is float)
# NOTE 2: Division always return always float result

#unary operators
print(-5)   #negates the value
print(+5)   #returns the operand value as it is
print(~5)   #bitwise not; increase the operand by 1 and negates it
print(not False)    #logical not; inverts the operant value
