# kilometer to miles converter; tip: 1 mile = 1.61 kilometers

kilometers = 4.5
miles = 2.5

kilometers_to_miles = kilometers * 1.61
miles_to_kilometers = miles / 1.61

print(kilometers, "kilometers is equal to", kilometers_to_miles, "miles")
print(miles, "miles is equal to", miles_to_kilometers, "kilometers")

print()

print(kilometers, "kilometers is equal to", round(kilometers_to_miles, 2), "miles")
print(miles, "miles is equal to", round(miles_to_kilometers, 2), "kilometers")
